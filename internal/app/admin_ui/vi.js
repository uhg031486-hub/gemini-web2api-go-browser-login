function translateVietnamese(value) {
  const text = String(value ?? '');
  const exact = I18N_VI[text.trim()];
  if (exact) return exact;
  return text.replace(/[\u3400-\u9fff]+/g, (phrase, offset) => {
    const translated = I18N_VI[phrase];
    if (!translated) return phrase;
    const before = offset > 0 && /[A-Za-z0-9]/.test(text[offset - 1]) ? ' ' : '';
    const end = offset + phrase.length;
    const after = end < text.length && /[A-Za-z0-9]/.test(text[end]) ? ' ' : '';
    return before + translated + after;
  }).replace(/，/g, ', ').replace(/。/g, '. ').replace(/：/g, ': ')
    .replace(/（/g, '(').replace(/）/g, ')').replace(/、/g, ', ')
    .replace(/「/g, '“').replace(/」/g, '”');
}
